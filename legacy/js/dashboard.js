/**
 * Generate a list of bet recommendations for a fixture.
 * @param {object} game
 * @param {object} pred  – result of predictMatch()
 * @returns {Array}
 */
function getBets(game, pred) {
  const bets = [];
  const fav  = pred.homeWin > pred.awayWin ? game.home : game.away;
  const favP = Math.max(pred.homeWin, pred.awayWin);
  const top  = pred.topScores[0];

  if (favP >= 0.60) bets.push({
    name: `Sieg ${fav}`,
    val:  `${Math.round(favP * 100)}%`,
    conf: favP >= 0.70 ? 'high' : 'medium',
    icon: '🏆',
    isTopPick: favP >= 0.65,
  });

  if (pred.over25 >= 0.58) bets.push({
    name: 'Über 2.5 Tore',
    val:  `${Math.round(pred.over25 * 100)}%`,
    conf: pred.over25 >= 0.70 ? 'high' : 'medium',
    icon: '⚽',
    isTopPick: pred.over25 >= 0.65,
  });

  if (pred.btts >= 0.55) bets.push({
    name: 'Beide Teams treffen',
    val:  `${Math.round(pred.btts * 100)}%`,
    conf: pred.btts >= 0.68 ? 'high' : 'medium',
    icon: '🎯',
    isTopPick: pred.btts >= 0.60,
  });

  if (pred.over35 >= 0.45) bets.push({
    name: 'Über 3.5 Tore',
    val:  `${Math.round(pred.over35 * 100)}%`,
    conf: 'medium',
    icon: '🔥',
    isTopPick: false,
  });

  if (pred.draw >= 0.28) bets.push({
    name: 'Unentschieden',
    val:  `${Math.round(pred.draw * 100)}%`,
    conf: 'medium',
    icon: '🤝',
    isTopPick: false,
  });

  bets.push({
    name: 'Ergebnis-Tipp',
    val:  `${top.h}:${top.a}`,
    conf: top.p >= 0.12 ? 'high' : top.p >= 0.08 ? 'medium' : 'low',
    icon: '📊',
    isTopPick: top.p >= 0.10,
  });

  return bets;
}


/* ─────────────────────────────────────────────────────
   2. POISSON ENGINE
   Uses Dixon-Coles-style attack/defence strength ratios
   applied against the historical WC average (1.42 g/team)
───────────────────────────────────────────────────── */

const GLOBAL_AVG = 1.42; // historical WC goals per team per match

/**
 * Return team stats, falling back to league-average defaults.
 * @param {string} name
 */
function getStats(name) {
  return TEAM_STATS[name] ?? { avg_scored: 1.3, avg_conceded: 1.1, win_rate: 0.4 };
}

/**
 * Poisson probability mass function P(X = k | λ).
 * @param {number} k      – number of goals
 * @param {number} lambda – expected goals
 */
function poissonPMF(k, lambda) {
  if (lambda <= 0) return k === 0 ? 1 : 0;
  let p = Math.exp(-lambda) * Math.pow(lambda, k);
  for (let i = 1; i <= k; i++) p /= i;
  return p;
}

/**
 * Predict a match between two teams.
 * @param {string} home
 * @param {string} away
 * @returns {object} prediction object
 */
function predictMatch(home, away) {
  const h = getStats(home);
  const a = getStats(away);

  // Attack / defence strength relative to global average
  const HOME_ADVANTAGE = 1.12;
  let lambdaH = (h.avg_scored / GLOBAL_AVG) * (a.avg_conceded / GLOBAL_AVG) * GLOBAL_AVG * HOME_ADVANTAGE;
  let lambdaA = (a.avg_scored / GLOBAL_AVG) * (h.avg_conceded / GLOBAL_AVG) * GLOBAL_AVG;

  // FIFA Ranking Boost (100 points diff ≈ 5% strength adjustment, max 20%)
  const homePoints = FIFA_RANKING[home]?.points || 1400; // Fallback ~Rank 70
  const awayPoints = FIFA_RANKING[away]?.points || 1400;
  const diff = homePoints - awayPoints;
  const rankFactor = Math.min(0.20, Math.max(-0.20, diff / 2000));
  
  lambdaH *= (1 + rankFactor);
  lambdaA *= (1 - rankFactor);

  // Clamp to sensible range
  lambdaH = Math.max(0.3, Math.min(lambdaH, 6));
  lambdaA = Math.max(0.3, Math.min(lambdaA, 6));

  // Build score probability matrix (0–7 goals each side)
  const MAX = 7;
  let homeWin = 0, draw = 0, awayWin = 0;
  const scores = [];

  for (let i = 0; i <= MAX; i++) {
    for (let j = 0; j <= MAX; j++) {
      const p = poissonPMF(i, lambdaH) * poissonPMF(j, lambdaA);
      scores.push({ h: i, a: j, p });
      if      (i > j)  homeWin += p;
      else if (i === j) draw   += p;
      else              awayWin += p;
    }
  }
  scores.sort((x, y) => y.p - x.p);

  const totalG = lambdaH + lambdaA;
  const btts   = (1 - poissonPMF(0, lambdaH)) * (1 - poissonPMF(0, lambdaA));

  return {
    lambdaH:    +lambdaH.toFixed(2),
    lambdaA:    +lambdaA.toFixed(2),
    homeWin:    +homeWin.toFixed(3),
    draw:       +draw.toFixed(3),
    awayWin:    +awayWin.toFixed(3),
    topScores:  scores.slice(0, 5),
    totalGoals: +totalG.toFixed(2),
    btts:       +btts.toFixed(3),
    over15:     +(1 - poissonPMF(0, totalG) - poissonPMF(1, totalG)).toFixed(3),
    over25:     +(1 - [0,1,2].reduce((s, k) => s + poissonPMF(k, totalG), 0)).toFixed(3),
    over35:     +(1 - [0,1,2,3].reduce((s, k) => s + poissonPMF(k, totalG), 0)).toFixed(3),
  };
}


/** State */
let currentFilter = 'all';
let searchTerm    = '';
let processed     = [];

/** Confidence badge Tailwind class maps */
const CONF_COLORS = {
  high:   { bg: 'bg-emerald-500/15', text: 'text-emerald-400', border: 'border-emerald-500/25' },
  medium: { bg: 'bg-gold/15',        text: 'text-gold-light',  border: 'border-gold/25'        },
  low:    { bg: 'bg-red-500/15',     text: 'text-red-400',     border: 'border-red-500/25'     },
};
const CONF_LABELS = { high: 'HOCH', medium: 'MITTEL', low: 'NIEDRIG' };

/** Render a confidence badge span. */
function confBadge(conf) {
  const c = CONF_COLORS[conf] ?? CONF_COLORS.low;
  return `<span class="font-mono text-xs md:text-sm font-semibold px-2 py-0.5 rounded ${c.bg} ${c.text} border ${c.border} shrink-0">${CONF_LABELS[conf]}</span>`;
}

/** Format an ISO date string to German locale. */
function formatDate(d) {
  return new Date(d + 'T12:00:00Z').toLocaleDateString('de-DE', {
    weekday: 'long', day: '2-digit', month: 'long', year: 'numeric',
  });
}

/** Apply active/inactive styles to all filter buttons. */
function updateFilterBtns() {
  document.querySelectorAll('.filter-btn').forEach(btn => {
    const active = btn.classList.contains('active');
    btn.style.background  = active ? '#d4a853'              : 'transparent';
    btn.style.borderColor = active ? '#d4a853'              : 'rgba(212,168,83,0.15)';
    btn.style.color       = active ? '#060a10'              : '#94a3b8';
    btn.style.fontWeight  = active ? '600'                  : '500';
  });
}

/** Switch the active filter and re-render. */
function setFilter(filter) {
  currentFilter = filter;
  document.querySelectorAll('.filter-btn').forEach(b => b.classList.remove('active'));
  document.getElementById('btn-' + filter).classList.add('active');
  updateFilterBtns();
  renderList();
}

/** Update search term and re-render. */
function onSearch(value) {
  searchTerm = value.trim().toLowerCase();
  renderList();
}

/** Return filtered game list based on active filter + search term. */
function getFiltered() {
  return processed.filter(g => {
    const matchesSearch = !searchTerm
      || g.home.toLowerCase().includes(searchTerm)
      || g.away.toLowerCase().includes(searchTerm);

    let matchesFilter = true;
    if (currentFilter === 'top')  matchesFilter = g.bets.some(b => b.isTopPick);
    if (currentFilter === 'over') matchesFilter = g.pred.over25 >= 0.58;
    if (currentFilter === 'fav')  matchesFilter = Math.max(g.pred.homeWin, g.pred.awayWin) >= 0.70;

    return matchesSearch && matchesFilter;
  });
}

/** Render the top stats bar. */
function renderStats() {
  const avgGoals = (processed.reduce((s, g) => s + g.pred.totalGoals, 0) / processed.length).toFixed(1);
  const topPicks = processed.filter(g => g.bets.some(b => b.isTopPick && b.conf === 'high')).length;
  const highOver = processed.filter(g => g.pred.over25 >= 0.65).length;

  const items = [
    { val: processed.length,               lbl: 'Spiele'            },
    { val: avgGoals,                        lbl: 'Ø Tore/Spiel'      },
    { val: topPicks,                        lbl: 'Top Picks'          },
    { val: highOver,                        lbl: 'Over 2.5 (≥65%)'   },
    { val: Object.keys(TEAM_STATS).length,  lbl: 'Teams analysiert'  },
  ];

  document.getElementById('statsbar').innerHTML = items.map((it, i) => `
    <div class="flex-1 max-w-[200px] py-6 px-6 text-center ${i < items.length - 1 ? 'border-r border-gold/10' : ''}">
      <div class="font-display text-4xl md:text-5xl text-gold leading-none">${it.val}</div>
      <div class="text-sm md:text-base text-slate-500 uppercase tracking-widest mt-2">${it.lbl}</div>
    </div>
  `).join('');
}

/** Render the batch betting recommendations panel. */
function renderBatch() {
  const topBets = [];
  processed.forEach(g => {
    g.bets
      .filter(b => b.isTopPick && (b.conf === 'high' || b.conf === 'medium'))
      .forEach(b => topBets.push({ ...b, home: g.home, away: g.away }));
  });

  // High-confidence first
  topBets.sort((a, b) => (b.conf === 'high' ? 1 : 0) - (a.conf === 'high' ? 1 : 0));
  const shown = topBets.slice(0, 12);

  const panel = document.getElementById('batch-panel');
  const ghost = panel.querySelector('span'); // keep BATCH ghost text
  panel.innerHTML = '';
  panel.appendChild(ghost);

  const title = document.createElement('div');
  title.className = 'font-display text-gold text-2xl md:text-3xl tracking-widest mb-4 flex items-center gap-2.5';
  title.innerHTML = `<span>⚡</span> Batch-Empfehlungen · Top ${shown.length} Tipps`;
  panel.appendChild(title);

  const grid = document.createElement('div');
  grid.className = 'grid gap-2.5';
  grid.style.gridTemplateColumns = 'repeat(auto-fill, minmax(260px, 1fr))';
  grid.innerHTML = shown.map(b => {
    const hF = FLAGS[b.home] ?? '🏴';
    const aF = FLAGS[b.away] ?? '🏴';
    return `
      <div class="flex items-center gap-3 md:gap-4 rounded-lg border border-gold/12 px-4 py-3
                  hover:border-gold/30 transition-all cursor-default"
           style="background:rgba(6,10,16,0.6)">
        <span class="text-xl md:text-2xl shrink-0">${b.icon}</span>
        <div class="flex-1 min-w-0 leading-snug">
          <div class="text-sm text-slate-500 truncate">${hF} ${b.home} — ${aF} ${b.away}</div>
          <div class="text-base md:text-lg font-semibold text-amber-100">${b.name}: <strong class="text-gold-light">${b.val}</strong></div>
        </div>
        ${confBadge(b.conf)}
      </div>`;
  }).join('');
  panel.appendChild(grid);
}

/** Render the main match list, grouped by date. */
function renderList() {
  const games = getFiltered();
  const el = document.getElementById('match-list');
  document.getElementById('count-label').textContent = `${games.length} Spiele`;

  if (!games.length) {
    el.innerHTML = `<div class="text-center py-20 text-slate-500 text-lg md:text-xl">Keine Spiele gefunden</div>`;
    return;
  }

  // Group games by date
  const byDate = {};
  games.forEach(g => { (byDate[g.date] = byDate[g.date] ?? []).push(g); });

  el.innerHTML = Object.entries(byDate).map(([date, gs]) => `
    <div class="day-group mb-8 animate-fade-up">
      <div class="flex items-center gap-4 mb-3.5">
        <h2 class="font-display text-gold tracking-widest text-xl md:text-2xl whitespace-nowrap">${formatDate(date)}</h2>
        <div class="flex-1 h-px bg-gold/10"></div>
        <span class="text-sm md:text-base text-slate-500 whitespace-nowrap font-mono">${gs.length} Spiel${gs.length > 1 ? 'e' : ''}</span>
      </div>
      ${gs.map(g => renderCard(g)).join('')}
    </div>
  `).join('');

  updateFilterBtns();
}


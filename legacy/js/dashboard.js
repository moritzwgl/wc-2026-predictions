/** Show a loading/error state in the match list area. */
function setStatus(msg, isError = false) {
  document.getElementById('match-list').innerHTML = `
    <div class="text-center py-20 ${isError ? 'text-red-400' : 'text-slate-500'} text-sm font-mono">
      ${msg}
    </div>`;
}

/** Pre-process all games: compute predictions + bets. */
function processGames() {
  processed = GAMES.map((g, i) => {
    const pred = predictMatch(g.home, g.away);
    const bets = getBets(g, pred);
    return { id: i, ...g, pred, bets };
  });
}

/**
 * Async entry point.
 * Loads data/team_stats.json and data/fixtures.json in parallel,
 * then builds predictions and renders the full UI.
 */
async function init() {
  setStatus('Lade Daten …');

  try {
    const [statsRes, fixturesRes, rankingRes] = await Promise.all([
      fetch('data/team_stats.json'),
      fetch('data/fixtures.json'),
      fetch('data/fifa_ranking.json'),
    ]);

    if (!statsRes.ok)    throw new Error(`team_stats.json: ${statsRes.status}`);
    if (!fixturesRes.ok) throw new Error(`fixtures.json: ${fixturesRes.status}`);
    if (!rankingRes.ok)  throw new Error(`fifa_ranking.json: ${rankingRes.status}`);

    TEAM_STATS = await statsRes.json();
    GAMES      = await fixturesRes.json();
    const rankArr = await rankingRes.json();
    rankArr.forEach(r => FIFA_RANKING[r.team] = { points: r.points, rank: r.rank });
  } catch (err) {
    setStatus(`Fehler beim Laden der Daten: ${err.message}`, true);
    console.error(err);
    return;
  }

  processGames();
  renderStats();
  renderBatch();
  renderList();
}

// Bootstrap
init();
